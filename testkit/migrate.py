"""Generate the runner families from tools/run_suite.py's steps (spec R13): every step not covered by the unit, fp and
programs families becomes a case of exactly one family, with its old claims (SERIAL_WHY, w, E_OK), smoke membership
(QUICK) and judge. Re-run after changing run_suite.py's steps: `python3 -m testkit.migrate`; the output is reviewed and
committed like any other test file.
"""
import fnmatch
import os
import pathlib
import sys

from testkit import paths

COVERED = {   # steps that other families now run
    'unit': ['build', 'cargo-test', 'cargo-test-fexc', 'runtime', 'release', 'pytests', 'split-wait-model'],
    'fp': ['i8', 'i8b', 'i8-1', 'i8b-1', 'i8-m2f', 'i8b-m2f', 'i8-m2a', 'i8b-m2a'],
    'programs': ['fix', 'seed', 'i9', 'i9-big', 'sha', 'adx', 'xsave', 'i10', 'rex', 'br66', 'i7', 'i7-cpl0', 'i6b', 'flow',
                 *[f'{c}-1' for c in ('fix', 'seed', 'i9', 'i9-big', 'sha', 'adx', 'xsave', 'i10', 'rex', 'br66', 'i7', 'i7-cpl0', 'i6b')]],
}
FAMILIES = [  # (family, patterns), first match wins
    ('static', ['stack', 'barriers']),
    ('boot', ['l1', 'l2', 'l2-iasl', 'boot-smoke']),
    ('io', ['io-coverage*', 'net-linux*', 'virtio-lifecycle*']),
    ('faults', ['faults@*', 'faults-1@*', 'i7-faults*', 'loopfaults-*', 'probes@*', 'i5c*', 'i5a-de*', 'i6-faults*',
                'i8-faults*', 'i9-faults*', 'i10-faults*', 'i6b-cases*']),
    ('smp', ['corpora-*', 'smp', 'litmus', 'limits', 'privilege', 'delivery', 'kicks', 'contain', 'system', 'coherence',
             'sharedpt', 'events', 'vector-*']),
    ('system', ['*']),
]
BUILDERS = {'l1', 'l2', 'l2-iasl', 'boot-smoke'}
# run_suite's w counts parallel VMs; these run --parallel 2 VMs of up to 4 vCPUs whose checks (lost races, litmus claims)
# need every vCPU on its own core at once
CORES = {'smp': 8, 'litmus': 8}


def toml_str(s): return '"' + str(s).replace('\\', '\\\\').replace('"', '\\"') + '"'


def main() -> int:
    sys.path.insert(0, str(paths.repo_root() / 'tools'))
    import run_suite
    FEXC, OUT = '/__FEXC__', pathlib.Path('/__OUT__')
    steps = run_suite.steps(FEXC, OUT)
    raw = str(run_suite.RAW)
    target = pathlib.Path(os.environ.get('CARGO_TARGET_DIR', run_suite.ROOT / 'target'))
    covered = {s for v in COVERED.values() for s in v}
    fams = {}
    for s in steps:
        if s.name in covered: continue
        fam = next(f for f, pats in FAMILIES if any(fnmatch.fnmatchcase(s.name, p) for p in pats))
        argv = []
        for a in s.argv:
            a = a.replace(FEXC, '{fexc}').replace(str(OUT / 'out' / s.name), '{out}').replace(raw, '{raw}')
            for rel, ph in (('release/natemu-host', '{natemu_host}'), ('aarch64-unknown-none/release/natemu-runtime', '{natemu_runtime}')):
                if a == str(target / rel): a = ph          # the framework's natemu build, not this checkout's target/
            argv.append(a)
        if argv[:1] == ['python3']: argv = argv[1:]
        if argv[:1] == ['tools/fexc/upstream_tests/run_asm.py'] and '--src' not in argv:
            argv += ['--src', '{fex_asm}']          # FEX's ASM tests from the framework (a fresh worktree's submodule is empty)
        needs = {}
        if s.phase == 'ser' or s.name in BUILDERS:
            needs = {'exclusive': True, 'why': run_suite.SERIAL_WHY.get(s.name, 'builds natemu in the worktree')}
        else:
            if s.w > 1 or s.name in CORES: needs['cores'] = CORES.get(s.name, s.w)
            if not any(fnmatch.fnmatch(s.name, p) for p in run_suite.E_OK): needs['perf'] = True
            if s.name in CORES: needs['mixed'] = True      # the whole machine where performance cores are too few (not an M1)
        case = {'argv': argv, 'needs': needs, 'smoke': any(fnmatch.fnmatch(s.name, p) for p in run_suite.QUICK),
                'builds': s.name in BUILDERS, 'rerun': s.phase == 'ser'}
        if s.judge: case['judge'] = f'judges:{s.judge.__name__}'
        fams.setdefault(fam, []).append((s.name, case))
    for fam, cases in fams.items():
        d = paths.repo_root() / 'tests' / fam
        d.mkdir(exist_ok=True)
        lines = [f'# Generated by `python3 -m testkit.migrate` from tools/run_suite.py (spec R13): the {fam} runners, each case one',
                 '# unchanged runner invocation with inputs from the input root and QEMU answers locked. Edit run_suite.py and regenerate.',
                 '[family]', f'name = "{fam}"', 'covers = ["crates/**", "third_party/FEX", "tools/**"]', '',
                 '[[suite]]', f'name = "{fam}"', 'kind = "judged"', 'harness = "runner"', 'params = { timeout = 3600 }', '']
        for name, c in cases:
            lines.append(f'[suite.cases.{toml_str(name)}]')
            lines.append('argv = [' + ', '.join(toml_str(a) for a in c['argv']) + ']')
            if c['needs']:
                lines.append('needs = { ' + ', '.join(f'{k} = {toml_str(v) if isinstance(v, str) else str(v).lower()}'
                                                     for k, v in c['needs'].items()) + ' }')
            for k in ('smoke', 'builds', 'rerun'):
                if c[k]: lines.append(f'{k} = true')
            if 'judge' in c: lines.append(f'judge = {toml_str(c["judge"])}')
            lines.append('')
        (d / 'family.toml').write_text('\n'.join(lines))
        print(f'{fam}: {len(cases)} cases')
    print(f'{len(steps)} steps: {len(covered & {s.name for s in steps})} covered by unit/fp/programs, '
          f'{sum(len(c) for c in fams.values())} in runner families')
    unmatched = covered - {s.name for s in steps}
    if unmatched: print('COVERED names that are not steps:', sorted(unmatched))
    return 0


if __name__ == '__main__': sys.exit(main())
