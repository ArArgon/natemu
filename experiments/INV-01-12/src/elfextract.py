#!/usr/bin/env python3
"""Extract .text and its symbols from an ELF64 x86-64 relocatable object.

Written because llvm-objcopy is not present in the Command Line Tools on the
host used for INV-01-12. Python 3 standard library only.

Usage: elfextract.py <guest.o> <guest_blob.h>

The guest program must be assembled so that .text needs no relocations (all
references are RIP-relative or immediate); any relocation entry against .text
is rejected rather than silently applied, because an unapplied relocation would
make the guest read a wrong address and quietly weaken the oracle.
"""

import struct
import sys

SHT_SYMTAB = 2
SHT_RELA = 4
SHT_REL = 9


def main(argv):
    if len(argv) != 3:
        sys.exit("usage: elfextract.py <object> <header>")
    data = open(argv[1], "rb").read()
    if data[:4] != b"\x7fELF" or data[4] != 2 or data[5] != 1:
        sys.exit("not a little-endian ELF64 object")
    e_shoff, = struct.unpack_from("<Q", data, 0x28)
    e_shentsize, e_shnum, e_shstrndx = struct.unpack_from("<HHH", data, 0x3A)

    sections = []
    for i in range(e_shnum):
        off = e_shoff + i * e_shentsize
        name, typ, flags, addr, offset, size, link, info, align, entsize = \
            struct.unpack_from("<IIQQQQIIQQ", data, off)
        sections.append(dict(name=name, type=typ, offset=offset, size=size,
                             link=link, info=info, entsize=entsize))

    shstr = sections[e_shstrndx]

    def sname(sec):
        base = shstr["offset"] + sec["name"]
        end = data.index(b"\0", base)
        return data[base:end].decode()

    text_idx = None
    for i, sec in enumerate(sections):
        if sname(sec) == ".text":
            text_idx = i
    if text_idx is None:
        sys.exit("no .text section")
    text = sections[text_idx]
    blob = data[text["offset"]:text["offset"] + text["size"]]

    for sec in sections:
        if sec["type"] in (SHT_RELA, SHT_REL) and sec["info"] == text_idx and sec["size"]:
            sys.exit("guest.o has %d bytes of relocations against .text; the guest "
                     "program must use only RIP-relative and immediate operands"
                     % sec["size"])

    syms = []
    for sec in sections:
        if sec["type"] != SHT_SYMTAB:
            continue
        strtab = sections[sec["link"]]
        n = sec["size"] // sec["entsize"]
        for i in range(n):
            off = sec["offset"] + i * sec["entsize"]
            nm, info, other, shndx, value, size = struct.unpack_from("<IBBHQQ", data, off)
            if shndx != text_idx or nm == 0:
                continue
            base = strtab["offset"] + nm
            end = data.index(b"\0", base)
            name = data[base:end].decode()
            if name.startswith(".") or name[0].isdigit():
                continue
            syms.append((name, value))
    syms.sort()

    with open(argv[2], "w") as f:
        f.write("/* Generated by src/elfextract.py from the assembled guest program.\n"
                "   Do not edit; regenerate with build.sh. */\n"
                "#ifndef GUEST_BLOB_H\n#define GUEST_BLOB_H\n\n")
        f.write("static const unsigned char guest_blob[] = {\n")
        for i in range(0, len(blob), 16):
            f.write("    " + ",".join("0x%02x" % b for b in blob[i:i + 16]) + ",\n")
        f.write("};\n\n")
        f.write("static const struct { const char *name; unsigned long off; } guest_syms[] = {\n")
        for name, value in syms:
            f.write('    {"%s", %dUL},\n' % (name, value))
        f.write("};\n\n#endif\n")
    print("guest .text: %d bytes, %d symbols" % (len(blob), len(syms)))


if __name__ == "__main__":
    main(sys.argv)
