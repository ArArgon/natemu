"""Generates `crates/abi/src/cpu_profile.rs`, the resident's copy of the presented CPU (`cpu_profile.json`), and its test
vectors: the answers of `cpu_profile.py` (the judge) for a matrix of CPUID inputs, MSR accesses and reset values, which
`crates/abi/src/cpu.rs` must reproduce. Data only: every value comes from the JSON through `cpu_profile.py`.

    python3 tools/models/gen_cpu_profile_rs.py           # rewrite the file
    python3 tools/models/gen_cpu_profile_rs.py --check   # exit 1 if it is stale (also tools/models/test_cpu_profile_rs.py)
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))
from models import cpu_profile as cp

OUT = pathlib.Path(__file__).resolve().parents[2] / 'crates/abi/src/cpu_profile.rs'
I = cp._i
ACCESS = {'none': 'NONE', 'ro': 'RO', 'rw': 'RW', 'owned-by-LAPIC': 'LAPIC'}
# Rules the resident checks itself; the others are implied by `access` and `writable` (always_gp*, reserved_gp,
# ucode_low32_zero, misc_enable: a set bit outside the writable mask is #GP) or by the LAPIC owner (lapic_owner).
RULE_BITS = {'canonical': 'CANONICAL', 'mtrr_type_low_byte': 'MTRR_TYPE_LOW_BYTE', 'mtrr_type_all_bytes': 'MTRR_TYPE_ALL_BYTES',
             'pat_type_all_bytes': 'PAT_TYPE_ALL_BYTES', 'apic_base_extd_needs_en': 'APIC_BASE_EXTD_NEEDS_EN', 'efer': 'EFER'}
CR0_START, EFER_START = 0x80010011, 0xd00          # the drivers' long-mode start-up controls (EFER context of the vectors)

# Inputs of the vectors.
VALUES = [0, 1, 2, 7, 0x80, 0x800, 0x8b, 0xd00, 0xd01, 0x500, 0x401, 0x1801, 0x401801, 0x1801 | 1 << 16, 0xc06, 0x206,
          0xfee00800, 0xfee00900, 0xfee00400, 0xfee00c00, 0xfee01800, 1 << 32, 0x1234 << 32, 0xffffffff, 0x0007040600070406,
          0x0606060606060606, 0x0202020202020202, 0x0706050403020100, 0x0000_7fff_ffff_f000, 0x0000_8000_0000_0000,
          0xffff_8000_0000_0000, 0xffff_7fff_ffff_ffff, 0xff80000800, 0xff80000400, 0x10000000006, 0x80000006, 1 << 63,
          cp.MASK64]
assert len(VALUES) <= 64


def leaves(p):
    subs = {0x4: range(6), 0x7: range(3), 0xB: (0, 1, 2, 3, 0x1ff), 0xD: range(4)}
    ls = sorted({k[0] for k in p.leaves} | {I(h) for h in p.d['cpuid_out_of_range']['holes_within_range']['holes_basic']}
                | {0x16, 0x20, 0x7fffffff, 0x40000001, 0x4fffffff, 0x50000000, 0x80000009, 0x8000ffff, 0xffffffff})
    return [(l, s) for l in ls for s in subs.get(l, (0, 5))]


def cpuid_vectors(p):
    base = dict(n=1, vcpu=0, cr4=0, apic_en=True, misc_enable=0x1801, xcr0=1)
    states = [base, dict(base, misc_enable=0x401801)]
    dynamic = [dict(base, n=n, vcpu=v) for n, v in ((2, 1), (4, 0), (4, 3), (3, 2))]
    dynamic += [dict(base, cr4=1 << 18), dict(base, apic_en=False), dict(base, xcr0=7), dict(base, xcr0=3),
                dict(base, n=4, vcpu=2, cr4=1 << 18, apic_en=False, xcr0=7)]
    out = []
    for leaf, sub in leaves(p):
        for st in states + (dynamic if leaf in (0, 1, 4, 0xB, 0xD, 0x80000001) else []):
            out.append((leaf, sub, st, p.cpuid(leaf, sub, **st)))
    return out


def write_ok(p, index, value):
    try:
        return p.msr_write_ok(index, value, cr0=CR0_START, efer=EFER_START)
    except ValueError:
        return False        # x2APIC MSR: #GP while IA32_APIC_BASE.EXTD = 0 (its reset; no transition is implemented)


def read_ok(p, index):
    try:
        return p.msr_read_ok(index)
    except ValueError:
        return False


def indices(p):
    """Every profile MSR (of the x2APIC range its ends and 0x802), the ends of every absent range, and unknown indices."""
    ends = {I(e[k]) for e in p.d['absent_msrs'] + p.d['msrs'] for k in ('index', 'index_last') if k in e}
    return sorted({i for i in p._msr if not 0x802 < i < 0x8ff} | ends | {0x0, 0x11, 0x12345678, 0xc0000104, 0xffffffff})


def h(v): return f'{v:#x}'


def render():
    p = cp.load()
    d, idn = p.d, p.d['identity']
    L = []
    w = L.append
    w('//! GENERATED by `tools/models/gen_cpu_profile_rs.py` from `tools/models/cpu_profile.json` (the presented CPU: CPU 16')
    w('//! as accepted with the CPU 17 compatibility registers, INV-03-01 CLM-03-01-16/-17; every value is sourced in the JSON).')
    w('//! Do not edit: rerun the generator; `tools/models/test_cpu_profile_rs.py` fails while this file is stale. The logic')
    w('//! that reads these tables is `crate::cpu`.')
    w('')
    w(f'pub const MAX_BASIC_LEAF: u32 = {idn["max_basic_leaf"]};')
    w(f'/// While IA32_MISC_ENABLE bit 22 is set (CPU 17).')
    w(f'pub const MAX_BASIC_LEAF_LIMITED: u32 = {idn["max_basic_leaf_limited"]};')
    w(f'pub const MAX_EXT_LEAF: u32 = {idn["max_ext_leaf"]};')
    w(f'pub const HYPERVISOR_LEAF: u32 = {idn["max_hypervisor_leaf"]};')
    w(f'pub const MAXLINADDR: u32 = {idn["maxlinaddr"]};')
    w(f'pub const MAXPHYADDR: u32 = {idn["maxphyaddr"]};')
    w(f'pub const TSC_HZ: u64 = {idn["tsc_hz"]};')
    w('/// `CPUID[i].1` of a leaf without subleaves.')
    w('pub const ANY: u32 = u32::MAX;')
    w('/// Static (leaf, subleaf, [EAX, EBX, ECX, EDX]); the dynamic fields are `crate::cpu::cpuid`\'s.')
    w(f'pub const CPUID: [(u32, u32, [u32; 4]); {len(d["cpuid"])}] = [')
    for e in d['cpuid']:
        sub = 'ANY' if e['subleaf'] is None else str(e['subleaf'])
        w(f'    ({e["leaf"]}, {sub}, [{", ".join(h(I(e[r])) for r in ("eax", "ebx", "ecx", "edx"))}]),')
    w('];')
    c = d['control']
    w(f'pub const CR0_VALID: u64 = {h(p.cr0_valid_mask())};')
    w('/// CR4 bits whose CPUID feature is advertised (SDM Vol.3 2.5); every other bit is reserved (#GP).')
    w(f'pub const CR4_VALID: u64 = {h(p.cr4_valid_mask())};')
    w(f'pub const EFER_VALID: u64 = {h(p.efer_valid_mask())};')
    w(f'pub const XCR0_RESET: u64 = {c["xcr0"]["reset"]};')
    w(f'pub const XCR0_VALID: [u64; {len(c["xcr0"]["valid_values"])}] = [{", ".join(c["xcr0"]["valid_values"])}];')
    w('')
    w('pub mod access {')
    for i, n in enumerate(ACCESS.values()):
        w(f'    pub const {n}: u8 = {i};')
    w('}')
    w('pub mod rule {')
    for i, n in enumerate(RULE_BITS.values()):
        w(f'    pub const {n}: u8 = 1 << {i};')
    w('}')
    w('/// An MSR (or the range `index..=last`): access, write rules, reset value and the bits a WRMSR may set.')
    w('#[derive(Clone, Copy, Debug, PartialEq, Eq)]')
    w('pub struct Msr {')
    w('    pub index: u32,')
    w('    pub last: u32,')
    w('    pub access: u8,')
    w('    pub rules: u8,')
    w('    pub reset: u64,')
    w('    pub writable: u64,')
    w('}')
    w(f'pub const MSRS: [Msr; {len(d["msrs"])}] = [')
    for e in d['msrs']:
        rules = ' | '.join(f'rule::{RULE_BITS[r]}' for r in e['write_rules'] if r in RULE_BITS) or '0'
        w(f'    Msr {{ index: {e["index"]}, last: {e.get("index_last", e["index"])}, access: access::{ACCESS[e["access"]]}, '
          f'rules: {rules}, reset: {e["reset"] or "0"}, writable: {e.get("writable_mask") or "0"} }}, // {e["name"]}')
    w('];')
    apic = next(e for e in d['msrs'] if I(e['index']) == 0x1b)
    w(f'/// IA32_APIC_BASE of the BSP (vCPU 0): bit 8 set.')
    w(f'pub const APIC_BASE_BSP_RESET: u64 = {apic["reset_bsp"]};')
    w(f'/// IA32_MISC_ENABLE bits a write commits; the others keep their reset value (CPU 17).')
    w(f'pub const MISC_ENABLE_COMMITTED: u64 = {p.msr(0x1a0)["committed_bits"]};')
    w('/// IA32_ARCH_CAPABILITIES bits the host adds at start-up when it reports FEAT_CSV3 (`crate::cpu::arch_capabilities`).')
    w(f'pub const ARCH_CAPABILITIES_CSV3: u64 = {p.msr(0x10a)["host_bits"]["mask"]};')
    st = p.mtrr_state()
    w(f'/// The virtual firmware\'s MTRR state (`parameters.mtrr_initial`, selected "{d["parameters"]["mtrr_initial"]["selected"]}":')
    w('/// RAM write-back, devices uncached; owner decision October 28), applied over the architectural reset.')
    w(f'pub const MTRR_INITIAL: [(u32, u64); {len(st)}] = [{", ".join(f"({h(k)}, {h(v)})" for k, v in sorted(st.items()))}];')
    w('')
    # ---- vectors ----
    w('/// `cpu_profile.py`\'s answers, for `crate::cpu`\'s tests.')
    w('#[cfg(test)]')
    w('pub mod vectors {')
    w(f'    pub const CR0: u64 = {h(CR0_START)};')
    w(f'    pub const EFER: u64 = {h(EFER_START)};')
    cv = cpuid_vectors(p)
    w('    /// (leaf, subleaf, vCPUs, vCPU, CR4, APIC_BASE.EN, MISC_ENABLE, XCR0) -> [EAX, EBX, ECX, EDX]')
    w(f'    pub const CPUID: [(u32, u32, u64, u64, u64, bool, u64, u64, [u32; 4]); {len(cv)}] = [')
    for leaf, sub, s, r in cv:
        w(f'        ({h(leaf)}, {sub}, {s["n"]}, {s["vcpu"]}, {h(s["cr4"])}, {str(s["apic_en"]).lower()}, {h(s["misc_enable"])}, '
          f'{s["xcr0"]}, [{", ".join(h(x) for x in r)}]),')
    w('    ];')
    w(f'    pub const VALUES: [u64; {len(VALUES)}] = [{", ".join(h(v) for v in VALUES)}];')
    ix = indices(p)
    w('    /// (index, RDMSR allowed, bit k: WRMSR of VALUES[k] allowed, at CR0/EFER above)')
    w(f'    pub const MSR: [(u32, bool, u64); {len(ix)}] = [')
    for i in ix:
        mask = sum(1 << k for k, v in enumerate(VALUES) if write_ok(p, i, v))
        w(f'        ({h(i)}, {str(read_ok(p, i)).lower()}, {h(mask)}),')
    w('    ];')
    me = [v for v in VALUES if write_ok(p, 0x1a0, v)]
    w('    /// IA32_MISC_ENABLE: accepted write -> value read back')
    w(f'    pub const MISC_ENABLE: [(u64, u64); {len(me)}] = [{", ".join(f"({h(v)}, {h(p.misc_enable_after_write(v))})" for v in me)}];')
    rs = [(i, I(p.msr(i)['reset'])) for i in sorted(p._msr) if p.msr(i)['access'] in ('rw', 'ro')]
    rs = [(i, st.get(i, v), st.get(i, I(p.msr(i).get('reset_bsp', v)))) for i, v in rs]
    w('    /// Readable MSR -> value after reset and the firmware MTRR state: (index, AP, BSP)')
    w(f'    pub const RESET: [(u32, u64, u64); {len(rs)}] = [')
    for i, ap, bsp in rs:
        w(f'        ({h(i)}, {h(ap)}, {h(bsp)}),')
    w('    ];')
    sizes = [2 << 20, 4 << 20, 1 << 30, (1 << 30) + (2 << 20), 0x70000000, 2 << 30, (2 << 30) + (2 << 20), (3 << 30) - (2 << 20), 3 << 30]
    w('    /// M2 addendum: guest RAM size -> the firmware\'s IA32_MTRR_DEF_TYPE and IA32_MTRR_PHYSBASE0..PHYSMASK7 (`mtrr_state(ram)`)')
    w(f'    pub const MTRR_FOR_RAM: [(u64, [(u32, u64); 17]); {len(sizes)}] = [')
    for r in sizes:
        st = p.mtrr_state(r)
        w(f'        ({h(r)}, [{", ".join(f"({h(k)}, {h(st.get(k, 0))})" for k in [0x2ff] + list(range(0x200, 0x210)))}]),')
    w('    ];')
    w('}')
    return '\n'.join(L) + '\n'


if __name__ == '__main__':
    text = render()
    if sys.argv[1:] == ['--check']:
        sys.exit(0 if OUT.read_text() == text else f'{OUT} is stale: run {sys.argv[0]}')
    OUT.write_text(text)
